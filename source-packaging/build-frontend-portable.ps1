# Portable, explicit-environment frontend build. Does not invoke ADB, SDK installation or license acceptance.
[CmdletBinding()]
param(
 [Parameter(Mandatory=$true)][string]$PythonExe,
 [Parameter(Mandatory=$true)][string]$SdkRoot,
 [Parameter(Mandatory=$true)][string]$JavaHome,
 [Parameter(Mandatory=$true)][string]$GradleExecutable,
 [string]$GradleUserHome=(Join-Path $PSScriptRoot '.gradle-cache'),
 [switch]$ValidateOnly,
 [switch]$RunUnitTests
)
$ErrorActionPreference='Stop'
$project=Split-Path $PSScriptRoot -Parent
$app=$project
$python=(Resolve-Path -LiteralPath $PythonExe).Path
$sdk=(Resolve-Path -LiteralPath $SdkRoot).Path
$jdk=(Resolve-Path -LiteralPath $JavaHome).Path
$gradle=(Resolve-Path -LiteralPath $GradleExecutable).Path
foreach($required in @((Join-Path $jdk 'bin\java.exe'),(Join-Path $sdk 'platforms\android-37.0\android.jar'),(Join-Path $sdk 'build-tools\36.0.0\aapt2.exe'))){
 if(-not(Test-Path -LiteralPath $required -PathType Leaf)){throw "Missing explicit build prerequisite: $required"}
}
# Verify source and native inputs before writing manifests or launching Gradle.
$env:NIUMA_PORTABLE_ROOT=$project
@'
from pathlib import Path
import os, hashlib, zipfile, importlib.util
p=Path(os.environ['NIUMA_PORTABLE_ROOT'])
expected='e7535ea421a25962eb2ea37c46ff867838e69d33ba6d935876ab84d108de5020'
a=p/'vendor/trime-v3.3.13-arm64-official.apk'
assert hashlib.sha256(a.read_bytes()).hexdigest()==expected, 'Official APK mismatch'
with zipfile.ZipFile(a) as z:
 data=z.read('lib/arm64-v8a/librime_jni.so')
 assert data==(p/'app/prebuilt/arm64-v8a/librime_jni.so').read_bytes(), 'Prebuilt native input differs from upstream'
spec=importlib.util.spec_from_file_location('portable_gesture_validation',p/'stage-gesture-data.py')
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
m.expected_payloads() # Source-file SHA, fixed oracle, deterministic generated bytes; read-only.
print('Pinned native and static source assets verified; no device access')
'@ | & $python -
if($LASTEXITCODE -ne 0){throw 'Portable input validation failed'}
$props=Join-Path $app 'local.properties'
$expectedProps='sdk.dir='+($sdk -replace '\\','/')+"`n"
if(Test-Path -LiteralPath $props){
 if([IO.File]::ReadAllText($props) -ne $expectedProps){throw 'local.properties targets another SDK; inspect it manually, never replace silently'}
}
Write-Output "Project: $app"
Write-Output "Python: $python"
Write-Output "SDK: $sdk"
Write-Output "Java: $jdk"
Write-Output "Gradle: $gradle"
if($ValidateOnly){Write-Output 'ValidateOnly: no staging, SDK/settings writes, Gradle or device operation';return}
# SDK licenses must already have been accepted by the builder through normal tooling.
if(-not(Test-Path -LiteralPath (Join-Path $sdk 'platforms\android-37.0\package.xml'))){throw 'Install API 37.0 using official SDK tooling first; no synthetic SDK metadata is generated here'}
if(-not(Test-Path -LiteralPath $props)){[IO.File]::WriteAllText($props,$expectedProps)}
& $python (Join-Path $project 'stage-custom-data.py')
if($LASTEXITCODE -ne 0){throw 'Custom source staging failed'}
& (Join-Path $project 'stage-custom-components.ps1')
& $python (Join-Path $project 'stage-associations.py')
if($LASTEXITCODE -ne 0){throw 'Association staging failed'}
& $python (Join-Path $project 'stage-gesture-data.py')
if($LASTEXITCODE -ne 0){throw 'Gesture staging failed'}
& $python (Join-Path $project 'offline-asr\stage_assets.py') --verify-staged
if($LASTEXITCODE -ne 0){throw 'Offline ASR packaged-input verification failed'}
& $python (Join-Path $project 'chime-check\stage_assets.py')
if($LASTEXITCODE -ne 0){throw 'Chime input staging failed'}
$env:JAVA_HOME=$jdk;$env:PATH="$jdk\bin;$env:PATH"
$env:ANDROID_HOME=$sdk;$env:ANDROID_SDK_ROOT=$sdk
$env:GRADLE_USER_HOME=$GradleUserHome;$env:BUILD_ABI='arm64-v8a'
$env:BUILD_VERSION_NAME='0.1.0'
$env:BUILD_GIT_REPO='https://github.com/osfans/trime'
$env:BUILD_COMMIT_HASH='b5cad1a49095a3652e9188982de400ca3a653f37+local-niuma-modifications'
$env:CI_NAME='NekogamiJam'
Push-Location $app
try {
 & $gradle --no-daemon --console=plain '-Pandroid.overridePathCheck=true' :app:assembleDebug
 if($LASTEXITCODE -ne 0){throw 'Portable frontend build failed'}
 if($RunUnitTests){
  & $gradle --no-daemon --console=plain '-Pandroid.overridePathCheck=true' :app:testDebugUnitTest --tests 'com.osfans.trime.data.theme.NiumaThemeTest' --tests 'com.osfans.trime.ime.glass.LiquidGlassStyleTest' --tests 'com.osfans.trime.ime.glass.MaterialApplyGateTest' --tests 'com.osfans.trime.ime.association.AssociationStateTest' --tests 'com.osfans.trime.ime.gesture.NiumaGestureRulesTest' --tests 'com.osfans.trime.ime.gesture.NiumaGestureExecutorTest' --tests 'com.osfans.trime.ime.ui.VectorGlyphsTest' --tests 'com.osfans.trime.ime.broadcast.EnterKeyGlyphTest' --tests 'com.osfans.trime.ime.gesture.ClearBeforeCursorPolicyTest' --tests 'com.osfans.trime.ime.voice.OfflineTranscriptPolicyTest' --tests 'com.osfans.trime.ime.english.ChimeModelTest' --tests 'com.osfans.trime.ime.english.EnglishEditorPolicyTest' --tests 'com.osfans.trime.ime.gesture.CursorWindowReaderTest'
  if($LASTEXITCODE -ne 0){throw 'Portable frontend unit tests failed'}
 }
} finally {Pop-Location}
Write-Output 'Frontend built from modified source with pinned prebuilt JNI; not a native-source rebuild or binary reproducibility attestation.'
