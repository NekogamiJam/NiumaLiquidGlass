#!/usr/bin/env python3
"""Stage pinned Niuma gesture data into the stable Trime source tree.

This is a local-only, fail-closed stager. It does not run automatically; review the
computed hashes and ownership manifest before invoking it in the target checkout.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
TOOL_DIR = ROOT / "gesture-tools"
APP_ROOT = ROOT
ASSET_DIR = APP_ROOT / "app" / "src" / "main" / "assets" / "niuma"
MANIFEST_PATH = ROOT / "vendor" / "gesture-assets.json"
CODE_PATHS = TOOL_DIR / "generated" / "niuma_code_paths.txt"
Z_TRANSITIONS = TOOL_DIR / "generated" / "niuma_z_transitions.json"
EXPECTED_INPUT = ROOT / "app" / "src" / "debug" / "assets" / "niuma" / "debug_expected.json"


def _load_generator() -> Any:
    module_path = TOOL_DIR / "build_z_transitions.py"
    spec = importlib.util.spec_from_file_location("niuma_gesture_data_generator", module_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load generator: {module_path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def expected_payloads() -> tuple[dict[str, bytes], dict[str, Any]]:
    generator = _load_generator()
    payload = generator.load_expected(EXPECTED_INPUT)
    expected_paths = generator.build_code_paths(payload)
    transition_doc = generator.build_document(payload, generator.sha256_file(EXPECTED_INPUT))
    expected_transitions = (json.dumps(transition_doc, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    source_hashes = {
        "app/src/debug/assets/niuma/debug_expected.json": generator.sha256_file(EXPECTED_INPUT),
        **{
            f"input-data/{name}": digest
            for name, digest in generator.SOURCE_SHA256.items()
        },
    }
    # Require the checked-in generated files to be byte-for-byte reproducible.
    checked_in = {
        "niuma_code_paths.txt": CODE_PATHS.read_bytes(),
        "niuma_z_transitions.json": Z_TRANSITIONS.read_bytes(),
    }
    expected = {
        "niuma_code_paths.txt": expected_paths,
        "niuma_z_transitions.json": expected_transitions,
    }
    for name, contents in expected.items():
        if checked_in[name] != contents:
            raise ValueError(f"checked-in generated bytes do not match pinned sources: {name}")
    return expected, source_hashes


def _read_previous_manifest() -> dict[str, Any] | None:
    if not MANIFEST_PATH.exists():
        return None
    try:
        value = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"existing ownership manifest is unreadable: {MANIFEST_PATH}") from exc
    if not isinstance(value, dict) or value.get("format") != 1 or value.get("managed_by") != "stage-gesture-data.py":
        raise ValueError("existing ownership manifest is not recognized; refusing to overwrite")
    if not isinstance(value.get("files"), dict):
        raise ValueError("existing ownership manifest has no valid files map")
    return value


def _manifest_owns(previous: dict[str, Any] | None, rel_path: str, target: Path) -> bool:
    if previous is None or not target.is_file():
        return False
    entry = previous["files"].get(rel_path)
    if not isinstance(entry, dict) or not isinstance(entry.get("sha256"), str):
        return False
    try:
        return sha256_file(target) == entry["sha256"]
    except OSError:
        return False


def stage() -> dict[str, Any]:
    expected, source_hashes = expected_payloads()
    previous = _read_previous_manifest()
    files: dict[str, dict[str, str]] = {}
    writes: list[tuple[Path, bytes, str]] = []
    for name, contents in expected.items():
        target = ASSET_DIR / name
        rel_path = target.relative_to(APP_ROOT).as_posix()
        digest = sha256_bytes(contents)
        files[rel_path] = {"sha256": digest, "bytes": str(len(contents))}
        if target.exists():
            if not target.is_file():
                raise ValueError(f"asset target is not a regular file: {target}")
            if target.read_bytes() != contents and not _manifest_owns(previous, rel_path, target):
                raise ValueError(f"refusing to overwrite unowned asset target: {target}")
            if target.read_bytes() == contents:
                continue
        writes.append((target, contents, rel_path))

    manifest = {
        "format": 1,
        "managed_by": "stage-gesture-data.py",
        "schema_id": "niuma_glass",
        "code_count": 170277,
        "source_sha256": source_hashes,
        "files": files,
    }
    manifest_bytes = (json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")
    if MANIFEST_PATH.exists():
        if not MANIFEST_PATH.is_file():
            raise ValueError(f"manifest target is not a regular file: {MANIFEST_PATH}")
        if MANIFEST_PATH.read_bytes() != manifest_bytes:
            previously_owned_all = previous is not None and all(
                _manifest_owns(previous, rel, ASSET_DIR / Path(rel).name)
                for rel in files
                if (ASSET_DIR / Path(rel).name).exists()
            )
            if not previously_owned_all:
                raise ValueError(f"refusing to overwrite unowned manifest: {MANIFEST_PATH}")

    # All targets are preflighted before the first write.
    for target, contents, _ in writes:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(contents)
    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_PATH.write_bytes(manifest_bytes)
    return manifest


if __name__ == "__main__":
    result = stage()
    print(f"staged {len(result['files'])} files; code_count={result['code_count']}")
